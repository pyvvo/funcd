// Package reference renders the Spec pages of funcd and funcdctl from the config struct and the command trees
// (ADR-0324).
package reference

import (
	"bytes"
	"fmt"
	"os"
	"strconv"
	"strings"
)

// Marker is the first line of each page's front matter.
const Marker = "# Generated by just generate from the config struct and the command trees: change the code, not this page."

// Page renders a Spec page: front matter that starts with Marker, then the sections in order.
func Page(title, description string, sections ...[]byte) []byte {
	var b bytes.Buffer
	b.WriteString("---\n" + Marker + "\n")
	b.WriteString("title: " + strconv.Quote(title) + "\n")
	b.WriteString("description: " + strconv.Quote(description) + "\n")
	b.WriteString("---\n")
	for _, section := range sections {
		b.WriteString("\n")
		b.Write(section)
	}
	return b.Bytes()
}

// Stale returns an error naming path when the file at path is missing or differs from page.
func Stale(path string, page []byte) error {
	got, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reference: %s cannot be read, run just generate: %w", path, err)
	}
	if !bytes.Equal(got, page) {
		return fmt.Errorf("reference: %s is stale, run just generate", path)
	}
	return nil
}

// cell makes text fit one Markdown table cell. The guide's pages are MDX, so the characters that open a tag or an
// expression become entities.
func cell(text string) string {
	return strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;").
		Replace(strings.Join(strings.Fields(text), " "))
}

// code wraps a non-empty value in a code span.
func code(value string) string {
	if value == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(value, "|", `\|`) + "`"
}
