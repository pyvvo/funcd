// Omitted kinds get no Spec: pyvvo/funcd#1438 removes the first four, and RuntimeClass gets its fields and its first
// reader with FEAT-0012 F139.
//
//nolint:gochecknoglobals // an immutable lookup table, the ADR's contract
var Omitted = []v1.Kind{v1.KindService, v1.KindGrant, v1.KindGateway, v1.KindWorkerNode, v1.KindRuntimeClass}

// Marker is the first front-matter line of every page Render writes; specgen deletes a page that carries it and that
// Render no longer returns.
const Marker = "# Generated by specgen from the Go types, api/types/v1alpha1/examples and the language shims' api.json: " +
	"change those, not this page."

// clients names the ctx clients whose methods a feature's Spec page lists, under its Handler API; "" is the context's
// own methods.
//
//nolint:gochecknoglobals // an immutable lookup table
var clients = map[string][]string{"services/kv": {"kv"}}

// language is a shim whose handler API a Spec page shows: its name and its api.json.
type language struct {
	name string
	api  []byte
}

// languages are the shims a Spec page shows, in the order it shows them.
//
//nolint:gochecknoglobals // an immutable lookup table
var languages = []language{{"TypeScript", shimnode.API}, {"Python", shimpython.API}}

// CommonPage is the page of the definitions every kind shares, relative to docs/guide.
const CommonPage = "develop/common-definitions.md"

//nolint:gochecknoglobals // an immutable lookup table
var common = []string{"ObjectMeta", "OwnerReference", "Condition"}

//nolint:gochecknoglobals // an immutable lookup table
var namedPatterns = map[string]string{
	`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`: "a DNS-1123 label",
	`^sha256:[a-f0-9]{64}$`:                "a sha256 digest",
}

// Render returns the generated pages by path relative to docs/guide: each feature's spec.md and CommonPage.
func Render(doc *huma.OpenAPI) (map[string][]byte, error) {
	pages, _, err := render(doc.Components.Schemas.Map(), Features)
	return pages, err
}

// Undescribed returns, sorted, the schema path ("FunctionSpec.handler") of every field that Render shows with no
// description.
func Undescribed(doc *huma.OpenAPI) []string {
	_, fields, _ := render(doc.Components.Schemas.Map(), Features)
	return undescribed(fields)
}

func undescribed(fields map[string]string) []string {
	var out []string
	for path, desc := range fields {
		if desc == "" {
			out = append(out, path)
		}
	}
	slices.Sort(out)
	return out
}

// render writes every page and returns, by schema path, the description of each field the pages show.
func render(schemas map[string]*huma.Schema, features []Feature) (map[string][]byte, map[string]string, error) {
	fields := map[string]string{}
	pages := map[string][]byte{}
	r := &renderer{schemas: schemas, fields: fields, anchors: map[string]string{}}
	for _, name := range common {
		r.anchors[name] = name
	}
	lines := front("Common definitions", "The definitions every kind shares: its metadata and the conditions of its status.")
	lines = append(lines, "", "Every kind shares these definitions, and each Spec page links to them.")
	for _, name := range common {
		s, ok := schemas[name]
		if !ok {
			return nil, nil, fmt.Errorf("kindref: the document has no %s schema", name)
		}
		r.section(name, 2, s, name, name)
	}
	pages[CommonPage] = page(append(lines, r.lines...))
	for _, f := range features {
		body, err := featurePage(schemas, fields, f)
		if err != nil {
			return nil, nil, err
		}
		pages["develop/"+f.Path+"/spec.md"] = body
	}
	return pages, fields, nil
}

func featurePage(schemas map[string]*huma.Schema, fields map[string]string, f Feature) ([]byte, error) {
	up := strings.Repeat("../", strings.Count(f.Path, "/")+1)
	r := &renderer{schemas: schemas, fields: fields, anchors: map[string]string{}, common: up + "common-definitions.md"}
	names := make([]string, len(f.Kinds))
	for i, k := range f.Kinds {
		names[i] = string(k)
	}
	list := join(names)
	title, description := list+" spec", "Every field of "+list+": its type, its limits and its description."
	if cs := clients[f.Path]; len(cs) > 0 {
		calls := make([]string, len(cs))
		for i, c := range cs {
			calls[i] = "ctx." + c
		}
		title = list + " spec and handler API"
		description = "Every field of " + list + ", then the methods a handler calls on " + join(calls) + "."
	}
	lines := front(title, description)
	lines = append(lines, "", "The spec and the status of each kind of this feature, as funcd's API schema states them. "+
		"The [Platform page]("+up+"../platform/"+f.Path+".md) explains the concept, and the `metadata` of every kind "+
		"is [the same]("+r.common+"#objectmeta).")
	for _, k := range f.Kinds {
		kind, ok := schemas[string(k)]
		if !ok {
			return nil, fmt.Errorf("kindref: the document has no %s schema", k)
		}
		r.lines = append(r.lines, "", "## "+string(k))
		if file := path.Base(f.Path) + "/" + strings.ToLower(string(k)) + ".yaml"; exists(file) {
			root := strings.Repeat("../", strings.Count(f.Path, "/")+4)
			r.lines = append(r.lines, "", "::include["+root+"api/types/v1alpha1/examples/"+file+"#"+strings.ToLower(string(k))+"]")
		}
		r.lines = append(r.lines, "", "| apiVersion | kind |", "| --- | --- |",
			"| `"+k.GVK().APIVersion()+"` | `"+string(k)+"` |")
		for _, part := range []string{"spec", "status"} {
			node, ok := kind.Properties[part]
			if !ok {
				continue
			}
			name, s := r.resolve(node)
			path := string(k) + "." + part
			owner := name
			if owner == "" {
				owner = path
			}
			r.anchors[name] = path
			r.section("`"+path+"`", 3, s, path, owner)
		}
	}
	if cs := clients[f.Path]; len(cs) > 0 {
		section, err := handlerSection(cs, languages)
		if err != nil {
			return nil, err
		}
		r.lines = append(r.lines, section...)
	}
	return page(append(lines, r.lines...)), nil
}

func exists(file string) bool {
	_, err := fs.Stat(examples.FS, file)
	return err == nil
}

// handlerAPI is a shim's api.json: each ctx client with its methods' signatures and docs.
type handlerAPI struct {
	Clients []handlerClient `json:"clients"`
}

type handlerClient struct {
	Name    string          `json:"name"`
	Doc     string          `json:"doc"`
	Methods []handlerMethod `json:"methods"`
}

type handlerMethod struct {
	Name      string `json:"name"`
	Signature string `json:"signature"`
	Doc       string `json:"doc"`
}

// handlerClients returns each language's view of the named ctx client, in the order of langs.
func handlerClients(name string, langs []language) ([]handlerClient, error) {
	out := make([]handlerClient, 0, len(langs))
	for _, lang := range langs {
		var api handlerAPI
		if err := json.Unmarshal(lang.api, &api); err != nil {
			return nil, fmt.Errorf("kindref: the %s shim's api.json: %w", lang.name, err)
		}
		i := slices.IndexFunc(api.Clients, func(c handlerClient) bool { return c.Name == name })
		if i < 0 {
			return nil, fmt.Errorf("kindref: the %s shim has no %s", lang.name, ctxName(name))
		}
		out = append(out, api.Clients[i])
	}
	return out, nil
}

// handlerSection lists, for each client, its methods in each language, from that language's own api.json: the
// languages name and describe their methods in their own way, so their tables stay apart. Overloads share a row.
func handlerSection(names []string, langs []language) ([]string, error) {
	lines := []string{"", "## Handler API", "", "The methods a handler calls on its context's clients, " +
		"in each language funcd ships a shim for."}
	for _, name := range names {
		views, err := handlerClients(name, langs)
		if err != nil {
			return nil, err
		}
		lines = append(lines, "", "### `"+ctxName(name)+"`")
		for i, c := range views {
			lines = append(lines, "", "#### "+langs[i].name, "", prose(c.Doc), "", "| Method | What it does |",
				"| --- | --- |")
			var order []string
			rows := map[string][]handlerMethod{}
			for _, m := range c.Methods {
				if _, seen := rows[m.Name]; !seen {
					order = append(order, m.Name)
				}
				rows[m.Name] = append(rows[m.Name], m)
			}
			for _, n := range order {
				var signatures []string
				doc := ""
				for _, m := range rows[n] {
					signatures = append(signatures, "`"+strings.ReplaceAll(m.Signature, "|", `\|`)+"`")
					if doc == "" {
						doc = m.Doc
					}
				}
				lines = append(lines, "| "+strings.Join(signatures, " or ")+" | "+prose(doc)+" |")
			}
		}
	}
	return lines, nil
}

// ctxName is how a handler reaches the client: ctx.<name>, or ctx for the context's own methods.
func ctxName(name string) string {
	if name == "" {
		return "ctx"
	}
	return "ctx." + name
}

// prose makes a doc comment fit a Markdown table cell of an MDX page: it escapes a pipe everywhere, and outside code
// spans the characters that open a tag or an expression. A code span opens with a run of backticks and closes at the
// next run of the same length, as CommonMark reads it, so a reStructuredText span between two double backticks stays
// code; a run that nothing closes is text.
func prose(text string) string {
	text = strings.Join(strings.Fields(text), " ")
	escape := strings.NewReplacer("|", `\|`, "<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;")
	var out strings.Builder
	for text != "" {
		open := strings.IndexByte(text, '`')
		if open < 0 {
			out.WriteString(escape.Replace(text))
			break
		}
		out.WriteString(escape.Replace(text[:open]))
		run := len(text[open:]) - len(strings.TrimLeft(text[open:], "`"))
		fence := text[open : open+run]
		end := closingRun(text[open+run:], run)
		if end < 0 {
			out.WriteString(fence)
			text = text[open+run:]
			continue
		}
		out.WriteString(fence + strings.ReplaceAll(text[open+run:open+run+end], "|", `\|`) + fence)
		text = text[open+run+end+run:]
	}
	return out.String()
}

// closingRun is the index in text of the first run of exactly n backticks, or -1.
func closingRun(text string, n int) int {
	for i := 0; i < len(text); {
		if text[i] != '`' {
			i++
			continue
		}
		j := i
		for j < len(text) && text[j] == '`' {
			j++
		}
		if j-i == n {
			return i
		}
		i = j
	}
	return -1
}

// renderer writes the field tables of one page. A schema the page already shows, or a common one, is linked rather
// than repeated.
type renderer struct {
	schemas map[string]*huma.Schema
	fields  map[string]string
	anchors map[string]string
	common  string
	lines   []string
}

type child struct {
	path, owner string
	schema      *huma.Schema
}

func (r *renderer) resolve(node *huma.Schema) (string, *huma.Schema) {
	ref := node.Ref
	if ref == "" && len(node.AllOf) == 1 {
		ref = node.AllOf[0].Ref
	}
	if ref == "" {
		return "", node
	}
	name := ref[strings.LastIndex(ref, "/")+1:]
	if s, ok := r.schemas[name]; ok {
		return name, s
	}
	return name, node
}

func (r *renderer) section(title string, level int, s *huma.Schema, path, owner string) {
	required := map[string]bool{}
	for _, k := range s.Required {
		required[k] = true
	}
	var nested []child
	rows := []string{"| Field | Type and limits | Description |", "| --- | --- | --- |"}
	for _, f := range slices.Sorted(maps.Keys(s.Properties)) {
		node := s.Properties[f]
		_, target := r.resolve(node)
		desc := node.Description
		if desc == "" {
			desc = target.Description
		}
		r.fields[owner+"."+f] = desc
		kind := r.describe(node, path+"."+f, owner+"."+f, required[f], &nested)
		rows = append(rows, "| `"+f+"` | "+cell(kind)+" | "+cell(escaped(desc))+" |")
	}
	r.lines = append(r.lines, "", strings.Repeat("#", level)+" "+title, "")
	r.lines = append(r.lines, rows...)
	for _, c := range nested {
		r.section("`"+c.path+"`", 3, c.schema, c.path, c.owner)
	}
}

// describe writes a field's type and limits, linking an object field to its section and queueing that section.
func (r *renderer) describe(node *huma.Schema, path, owner string, required bool, nested *[]child) string {
	name, s := r.resolve(node)
	var parts, each []string
	switch {
	case s.Type == huma.TypeArray && s.Items != nil:
		itemName, item := r.resolve(s.Items)
		if len(item.Properties) > 0 {
			parts = append(parts, "array of "+r.link(itemName, path+"[]", owner+"[]", item, nested))
		} else {
			parts = append(parts, "array of "+scalar(item)+" values")
			for _, l := range limits(item) {
				each = append(each, "each "+l)
			}
		}
	case len(s.Properties) > 0:
		parts = append(parts, "object, "+r.link(name, path, owner, s, nested))
	case s.Type == huma.TypeObject && mapOf(s) != nil:
		valueName, v := r.resolve(mapOf(s))
		if len(v.Properties) > 0 {
			parts = append(parts, "map of string to "+r.link(valueName, path+".*", owner+".*", v, nested))
		} else {
			parts = append(parts, "map of string to "+scalar(v))
		}
	default:
		parts = append(parts, scalar(s))
	}
	if required {
		parts = append(parts, "required")
	}
	parts = append(parts, limits(s)...)
	return strings.Join(append(parts, each...), ", ")
}

func (r *renderer) link(name, path, owner string, s *huma.Schema, nested *[]child) string {
	if slices.Contains(common, name) {
		return "[" + name + "](" + r.common + "#" + slug(name) + ")"
	}
	if at, ok := r.anchors[name]; ok && name != "" {
		return "[`" + at + "`](#" + slug(at) + ")"
	}
	if name != "" {
		r.anchors[name] = path
		owner = name
	}
	*nested = append(*nested, child{path: path, owner: owner, schema: s})
	return "[`" + path + "`](#" + slug(path) + ")"
}

// mapOf is the schema of a map's values, nil when s is no map.
func mapOf(s *huma.Schema) *huma.Schema {
	values, _ := s.AdditionalProperties.(*huma.Schema)
	return values
}

func scalar(s *huma.Schema) string {
	if s.Type == "" {
		return "any JSON value"
	}
	return s.Type
}

func limits(s *huma.Schema) []string {
	var out []string
	if len(s.Enum) > 0 {
		values := make([]string, len(s.Enum))
		for i, v := range s.Enum {
			raw, _ := json.Marshal(v) // an enum value is a JSON value
			values[i] = "`" + shown(raw) + "`"
		}
		out = append(out, "one of "+strings.Join(values, ", "))
	}
	named, isNamed := namedPatterns[s.Pattern]
	switch {
	case s.Pattern == "":
	case s.PatternDescription != "":
		out = append(out, s.PatternDescription)
	case isNamed:
		out = append(out, named)
	default:
		out = append(out, "matching `"+s.Pattern+"`")
	}
	switch {
	case s.Minimum != nil && s.Maximum != nil:
		out = append(out, number(*s.Minimum)+" to "+number(*s.Maximum))
	case s.Minimum != nil:
		out = append(out, "at least "+number(*s.Minimum))
	case s.Maximum != nil:
		out = append(out, "at most "+number(*s.Maximum))
	}
	if !isNamed {
		switch {
		case s.MaxLength != nil:
			lo := 0
			if s.MinLength != nil {
				lo = *s.MinLength
			}
			out = append(out, fmt.Sprintf("%d to %d characters", lo, *s.MaxLength))
		case s.MinLength != nil && *s.MinLength > 0:
			out = append(out, fmt.Sprintf("at least %d characters", *s.MinLength))
		}
	}
	if s.Default != nil {
		raw, _ := json.Marshal(s.Default) // a default is a JSON value
		out = append(out, "default `"+shown(raw)+"`")
	}
	return out
}

// shown is how a page writes a schema value: a non-empty string as it is, anything else as JSON.
func shown(raw []byte) string {
	var s string
	if json.Unmarshal(raw, &s) == nil && s != "" {
		return s
	}
	return string(raw)
}

func number(f float64) string { return strconv.FormatFloat(f, 'f', -1, 64) }

var unslugged = regexp.MustCompile(`[^a-z0-9 _-]`)

// slug is the heading id the site gives a heading (github-slugger, which fumadocs uses).
func slug(heading string) string {
	return strings.ReplaceAll(unslugged.ReplaceAllString(strings.ToLower(heading), ""), " ", "-")
}

// escaped writes as entities the characters of a description that Markdown and MDX would read as markup: <name> as an
// HTML tag, {} as an expression. The funcd and funcdctl Spec pages escape them the same way.
func escaped(desc string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;", "{", "&#123;", "}", "&#125;").Replace(desc)
}

func cell(text string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(text), " "), "|", `\|`)
}

func join(names []string) string {
	if len(names) < 2 {
		return strings.Join(names, "")
	}
	return strings.Join(names[:len(names)-1], ", ") + " and " + names[len(names)-1]
}

func front(title, description string) []string {
	return []string{"---", Marker, "title: " + strconv.Quote(title), "description: " + strconv.Quote(description), "---"}
}

func page(lines []string) []byte { return []byte(strings.Join(lines, "\n") + "\n") }
