// Command specgen writes the huma-generated OpenAPI 3.1 spec to the committed path.
// It builds the API with stub handlers and writes the YAML output deterministically. With -guide, it also writes the
// guide's Spec pages (ADR-0323) and the API reference's layout beside them (ADR-0331).
// Usage: go run ./cmd/specgen/ -out ../../api/openapi/funcd.v1alpha1.yaml [-guide ../../docs/guide]
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"strings"

	"github.com/danielgtaylor/huma/v2"

	"github.com/pyvvo/funcd/internal/controlplane"
	"github.com/pyvvo/funcd/internal/controlplane/kindref"
)

func main() {
	outPath := flag.String("out", "api/openapi/funcd.v1alpha1.yaml", "output path for the OpenAPI YAML spec")
	guide := flag.String("guide", "", "the user guide's directory, a repository's docs/guide: write each feature's Spec "+
		"page under it (ADR-0323), and the API reference's layout (ADR-0331)")
	flag.Parse()

	api := controlplane.SpecAPI()

	raw, yamlErr := api.OpenAPI().YAML()
	if yamlErr != nil {
		fmt.Fprintf(os.Stderr, "specgen: failed to generate YAML: %v\n", yamlErr)
		os.Exit(1)
	}

	// Canonicalize: sort keys for deterministic output.
	canonical := string(raw)
	if !strings.HasPrefix(canonical, "# Generated by funcd specgen") {
		canonical = "# Generated by funcd specgen — DO NOT EDIT.\n# This file is derived from typed Go operations and committed for CI staleness checking.\n\n" + canonical
	}

	// Sort map keys deterministically.
	canonical = canonicalizeYAML(canonical)

	if err := os.WriteFile(*outPath, []byte(canonical), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "specgen: failed to write spec: %v\n", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "specgen: wrote %s\n", *outPath)

	if *guide != "" {
		err := writeGuide(*guide, api.OpenAPI())
		if err == nil {
			err = writeReference(*guide, api.OpenAPI())
		}
		if err != nil {
			fmt.Fprintf(os.Stderr, "specgen: %v\n", err)
			os.Exit(1)
		}
	}
}

// writeGuide writes the Spec pages under dir and deletes each page under its develop/ folder that carries the
// generated marker and that kindref no longer renders (ADR-0323 Decision 1).
func writeGuide(dir string, doc *huma.OpenAPI) error {
	pages, err := kindref.Render(doc)
	if err != nil {
		return err
	}
	for rel, body := range pages {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, body, 0o644); err != nil {
			return err
		}
	}
	root := filepath.Join(dir, "develop")
	return filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".md" {
			return err
		}
		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		if _, ok := pages[filepath.ToSlash(rel)]; ok || !generated(path) {
			return nil
		}
		fmt.Fprintf(os.Stderr, "specgen: removed %s\n", rel)
		return os.Remove(path)
	})
}

// writeReference writes the API reference's layout, whose files kindref names from the repository root: the
// repository that holds guide as its docs/guide. It reads the title and icon of each section of the guide's Develop
// chapter, and deletes each meta.json under the guide's api folder that kindref no longer returns, with each folder
// that this leaves empty (ADR-0331 Decision 3.2).
func writeReference(guide string, doc *huma.OpenAPI) error {
	guide = filepath.Clean(guide)
	if filepath.Base(guide) != "guide" || filepath.Base(filepath.Dir(guide)) != "docs" {
		return fmt.Errorf("the guide %s is not a repository's docs/guide, from whose root the API reference's files are named", guide)
	}
	root := filepath.Dir(filepath.Dir(guide))
	sections, err := guideSections(filepath.Join(guide, "develop"))
	if err != nil {
		return err
	}
	files, err := kindref.ReferenceFiles(doc, sections)
	if err != nil {
		return err
	}
	for rel, body := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, body, 0o644); err != nil {
			return err
		}
	}
	return removeStale(root, filepath.Join(guide, "api"), files)
}

// guideSections reads the title and icon of each section of the Develop chapter: a folder of develop with a
// meta.json, by the folder's name.
func guideSections(develop string) (map[string]kindref.SectionMeta, error) {
	entries, err := os.ReadDir(develop)
	if err != nil {
		return nil, err
	}
	sections := map[string]kindref.SectionMeta{}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		path := filepath.Join(develop, e.Name(), "meta.json")
		b, err := os.ReadFile(path)
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		var section kindref.SectionMeta
		if err := json.Unmarshal(b, &section); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		sections[e.Name()] = section
	}
	return sections, nil
}

// removeStale deletes each meta.json under dir whose path from root files does not hold, then each folder under dir
// that this leaves empty.
func removeStale(root, dir string, files map[string][]byte) error {
	var folders []string
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case d.IsDir():
			if path != dir {
				folders = append(folders, path)
			}
			return nil
		case d.Name() != "meta.json":
			return nil
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		if _, ok := files[filepath.ToSlash(rel)]; ok {
			return nil
		}
		fmt.Fprintf(os.Stderr, "specgen: removed %s\n", rel)
		return os.Remove(path)
	})
	if err != nil {
		return err
	}
	// WalkDir lists a folder before the folders in it, so the reverse order empties a folder's children first.
	slices.Reverse(folders)
	for _, folder := range folders {
		entries, err := os.ReadDir(folder)
		if err != nil {
			return err
		}
		if len(entries) == 0 {
			if err := os.Remove(folder); err != nil {
				return err
			}
		}
	}
	return nil
}

// generated reports whether the page at path carries kindref's marker as its front matter's first line.
func generated(path string) bool {
	b, err := os.ReadFile(path)
	return err == nil && strings.HasPrefix(string(b), "---\n"+kindref.Marker+"\n")
}

// canonicalizeYAML reorders top-level map keys for deterministic output.
// huma's YAML emitter uses Go maps which have non-deterministic iteration order.
func canonicalizeYAML(raw string) string {
	lines := strings.Split(raw, "\n")

	// Prepend header if missing.
	if !strings.HasPrefix(raw, "# Generated by funcd specgen") {
		lines = append([]string{
			"# Generated by funcd specgen — DO NOT EDIT.",
			"# This file is derived from typed Go operations and committed for CI staleness checking.",
			"",
		}, lines...)
	}

	// Sort the 'paths' entries if they exist.
	result := strings.Join(lines, "\n")
	result = sortPathsSection(result)
	return result
}

// sortPathsSection sorts paths within the OpenAPI 'paths:' block alphabetically.
func sortPathsSection(raw string) string {
	// Find the 'paths:' section and sort its entries.
	// This is a simple line-based sort that handles the common huma output format.
	idx := strings.Index(raw, "\npaths:\n")
	if idx < 0 {
		return raw
	}

	// Collect path entries until next top-level key or end.
	rest := raw[idx+len("\npaths:\n"):]
	var entries []string
	current := ""
	depth := 0
	for _, line := range strings.Split(rest, "\n") {
		if depth == 0 && (line == "" || (len(line) > 0 && line[0] != ' ' && line[0] != '\t')) {
			// We hit a top-level key or empty line — flush current entry.
			if current != "" {
				entries = append(entries, strings.TrimRight(current, "\n"))
			}
			if line == "" {
				continue
			}
			// This is the next top-level key — we're done with paths.
			current = ""
			break
		}
		if depth == 0 && len(line) > 0 && (line[0] == ' ' || line[0] == '\t') {
			current += line + "\n"
			// Count leading spaces for depth.
			leading := 0
			for _, c := range line {
				if c == ' ' {
					leading++
				} else {
					break
				}
			}
			depth = leading
		} else if depth > 0 && len(line) > 0 && strings.HasPrefix(line, strings.Repeat(" ", depth)) {
			current += line + "\n"
		} else if line == "" && current != "" {
			current += line + "\n"
		} else {
			if current != "" {
				entries = append(entries, strings.TrimRight(current, "\n"))
			}
			current = ""
			depth = 0
			if line != "" {
				current = line + "\n"
				depth = 0
			}
		}
	}
	if current != "" {
		entries = append(entries, strings.TrimRight(current, "\n"))
	}

	if len(entries) <= 1 {
		return raw
	}

	sort.Slice(entries, func(i, j int) bool {
		// Extract the path key (first non-empty line, trim leading /{path}).
		pi := strings.TrimSpace(strings.SplitN(entries[i], "\n", 2)[0])
		pj := strings.TrimSpace(strings.SplitN(entries[j], "\n", 2)[0])
		return pi < pj
	})

	sorted := raw[:idx] + "\npaths:\n"
	for _, e := range entries {
		sorted += e + "\n"
	}
	// Append remaining content after paths.
	afterPaths := rest
	for _, e := range entries {
		afterPaths = strings.Replace(afterPaths, e+"\n", "", 1)
	}
	sorted += afterPaths
	return sorted
}
