// ===== scenario: spec-generated-from-go =====

func TestSpecGeneratedFromGo(t *testing.T) {
	_ = fault.Problem{} // use fault import

	h := controlplane.NewStubHandlers()
	r := chi.NewRouter()
	api := controlplane.NewAPI(r, h)
	controlplane.RegisterStubLogs(api)            // ADR-0084: the logs route is part of the committed spec
	controlplane.RegisterStubWorkflowRunLogs(api) // ADR-0106: the run-scoped logs route is part of the committed spec
	controlplane.RegisterStubDeadLetters(api)     // ADR-0118: the DLQ read + replay/discard routes are part of the committed spec

	raw, err := api.OpenAPI().YAML()
	if err != nil {
		t.Fatalf("failed to generate YAML: %v", err)
	}

	committed, err := os.ReadFile("../../api/openapi/funcd.v1alpha1.yaml")
	if err != nil {
		t.Skipf("committed spec not found: %v", err)
		return
	}

	// Strip the specgen header from the committed spec for comparison.
	committedStr := string(committed)
	committedStr = strings.TrimPrefix(committedStr, "# Generated by funcd specgen — DO NOT EDIT.\n")
	committedStr = strings.TrimPrefix(committedStr, "# This file is derived from typed Go operations and committed for CI staleness checking.\n")
	committedStr = strings.TrimPrefix(committedStr, "\n")

	generated := string(raw)
	if generated != committedStr {
		t.Errorf("generated spec differs from committed spec.\nGenerated: %d bytes, Committed: %d bytes\nFirst diff at byte %d\nGenerated prefix:\n%s\n\nCommitted prefix:\n%s",
			len(generated), len(committedStr),
			firstDiff(generated, committedStr),
			trunc(generated, 300),
			trunc(committedStr, 300))
	}
}

