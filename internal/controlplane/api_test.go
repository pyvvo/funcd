// ===== helpers =====

func minint(a, b int) int {
	if a < b {
		return a
	}
	return b
}

func trunc(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}

func firstDiff(a, b string) int {
	n := minint(len(a), len(b))
	for i := 0; i < n; i++ {
		if a[i] != b[i] {
			return i
		}
	}
	if len(a) != len(b) {
		return n
	}
	return -1
}

// ===== scenario: schema-rejects-invalid-dto =====
// huma validates the request body against the generated schema BEFORE the handler runs:
// the DNS-1123 name pattern (ObjectName SchemaProvider) and replicas>=0 (struct tag) are
// enforced at the edge, returning 422 — proving both validation mechanisms are wired.
func TestSchemaRejectsInvalidDTO(t *testing.T) {
	h := controlplane.NewStubHandlers()
	r := chi.NewRouter()
	api := controlplane.NewAPI(r, h)
	ta := humatest.Wrap(t, api)
	const path = "/apis/funcd.io/v1alpha1/namespaces/my-ns/functions"

	badName := map[string]interface{}{
		"metadata": map[string]interface{}{"name": "Bad_Name!", "namespace": "my-ns", "resourceGroup": "rg1"},
		"spec":     map[string]interface{}{"runtime": "nodejs22"},
	}
	if resp := ta.Post(path, "Content-Type: application/json", badName); resp.Code != http.StatusUnprocessableEntity {
		t.Fatalf("bad DNS-1123 name: want 422 (schema pattern), got %d: %s", resp.Code, resp.Body.String())
	}

	negReplicas := map[string]interface{}{
		"metadata": map[string]interface{}{"name": "ok-name", "namespace": "my-ns", "resourceGroup": "rg1"},
		"spec":     map[string]interface{}{"runtime": "nodejs22", "replicas": -1},
	}
	if resp := ta.Post(path, "Content-Type: application/json", negReplicas); resp.Code != http.StatusUnprocessableEntity {
		t.Fatalf("negative replicas: want 422 (schema minimum:0), got %d: %s", resp.Code, resp.Body.String())
	}

	overCap := map[string]interface{}{
		"metadata": map[string]interface{}{"name": "ok-name", "namespace": "my-ns", "resourceGroup": "rg1"},
		"spec":     map[string]interface{}{"runtime": "nodejs22", "replicas": 16},
	}
	if resp := ta.Post(path, "Content-Type: application/json", overCap); resp.Code != http.StatusUnprocessableEntity {
		t.Fatalf("replicas over cap: want 422 (schema maximum:15), got %d: %s", resp.Code, resp.Body.String())
	}

	// new schema leaves: a bad runtime (RuntimeName DNS-1123) and a bad handler (handlerPattern).
	for _, bad := range []struct {
		what string
		spec map[string]interface{}
	}{
		{"runtime", map[string]interface{}{"runtime": "Bad_Runtime!", "handler": "h"}},
		{"handler", map[string]interface{}{"runtime": "nodejs22", "handler": "1-bad-handler"}},
	} {
		body := map[string]interface{}{
			"metadata": map[string]interface{}{"name": "ok-name", "namespace": "my-ns", "resourceGroup": "rg1"},
			"spec":     bad.spec,
		}
		if resp := ta.Post(path, "Content-Type: application/json", body); resp.Code != http.StatusUnprocessableEntity {
			t.Fatalf("bad %s: want 422 (schema), got %d: %s", bad.what, resp.Code, resp.Body.String())
		}
	}
}

// ===== scenario: site-requires-ingress (ADR-0139) =====
// A Site's ingress is required in V1: the generated schema marks it required, so a body without it is
// rejected at the edge (422) before any handler runs; the same body with an ingress is created (201).
// Validate() cannot see the absence of a value-typed field, so the wire schema is the enforcement path.
func TestScenarioSiteSchemaRequiresIngress(t *testing.T) {
	h := controlplane.NewStubHandlers()
	r := chi.NewRouter()
	api := controlplane.NewAPI(r, h)
	ta := humatest.Wrap(t, api)
	const path = "/apis/funcd.io/v1alpha1/namespaces/my-ns/sites"

	spec := map[string]interface{}{
		"image":  "oci-layout:///layout:bi",
		"bucket": map[string]interface{}{"name": "reports"},
		"prefix": "bi",
	}
	body := map[string]interface{}{
		"apiVersion": "funcd.io/v1alpha1",
		"kind":       "Site",
		"metadata":   map[string]interface{}{"name": "bi", "namespace": "my-ns", "resourceGroup": "rg1"},
		"spec":       spec,
	}
	if resp := ta.Post(path, "Content-Type: application/json", body); resp.Code != http.StatusUnprocessableEntity {
		t.Fatalf("missing spec.ingress: want 422 (schema required), got %d: %s", resp.Code, resp.Body.String())
	}
	spec["ingress"] = map[string]interface{}{"host": "bi.example.com"}
	if resp := ta.Post(path, "Content-Type: application/json", body); resp.Code != http.StatusOK && resp.Code != http.StatusCreated {
		t.Fatalf("with spec.ingress: want 2xx, got %d: %s", resp.Code, resp.Body.String())
	}
}

// ===== scenario: control-plane-body-over-cap (ADR-0148) =====
// A body over huma's 1 MiB MaxBodyBytes answers funcd's PayloadTooLarge problem, not huma's about:blank.
func TestScenarioControlPlaneBodyOverCap(t *testing.T) {
	ta := humatest.Wrap(t, controlplane.NewAPI(chi.NewRouter(), controlplane.NewStubHandlers()))
	body := strings.NewReader(`{"metadata":{"name":"` + strings.Repeat("x", 1<<20) + `"}}`)
	resp := ta.Post("/apis/funcd.io/v1alpha1/namespaces/my-ns/functions", "Content-Type: application/json", body)
	if resp.Code != http.StatusRequestEntityTooLarge {
		t.Fatalf("want 413, got %d: %.300s", resp.Code, resp.Body.String())
	}
	if ct := resp.Header().Get("Content-Type"); ct != "application/problem+json" {
		t.Errorf("want application/problem+json, got %q", ct)
	}
	var p fault.Problem
	if err := json.Unmarshal(resp.Body.Bytes(), &p); err != nil {
		t.Fatalf("decode problem: %v", err)
	}
	if p.Type != "urn:funcd:problem:payload-too-large" || p.Title != "Content Too Large" || p.Status != http.StatusRequestEntityTooLarge {
		t.Fatalf("want funcd's payload-too-large problem, got %+v", p)
	}
}
